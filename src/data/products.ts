/* El slug —la dirección propia de cada producto, /producto/<slug>— lo pone la
   base cuando el catálogo es real (ver supabase/parches/slugs-y-seo.sql). Para
   el catálogo de arranque se calcula acá: sin slug, la tarjeta no linkea a
   ningún lado y la ficha no se puede ni abrir para trabajar en el diseño. */
function slugificar(texto: string): string {
  return texto
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export const products: Product[] = CRUDOS.map((p) => ({
  ...p,
  slug: p.slug ?? slugificar(p.title),
}));
